# @title 【不具合例】終了コードが 256 ずれる
# @desc テストは合っているのに落ちるとき
#
# 終了コードは OS が下位 8 ビットしか受け取らない。
# main が 300 を返しても、シェルや test_runner が見る値は 300 - 256 = 44 になる。
# 計算そのものは正しいのに「期待値と 256 ずれる」ときはこれを疑う。
#
# 確かめたい値が 255 を超えるなら、終了コードではなく printf で出す。

  .text
  .globl main
main:
  addi sp, sp, -16
  sd ra, 8(sp)

  li a0, 100
  li a1, 3
  mul a0, a0, a1          # 300

  ld ra, 8(sp)
  addi sp, sp, 16
  ret                     # 300 を返すが、終了コードは 44 になる
