// フィールド宣言の間に行コメントがあっても、構文解析の結果から
// レイアウトを作るので、後続のフィールドが消えたりしない。
struct S {
    int x;    // 先頭フィールド
    // 独立行のコメント
    int y;    // 2 番目のフィールド
    char *p;  // ポインタフィールド
};

int main() {
    struct S s;
    s.x = 3;
    s.y = 4;
    s.p = 0;
    // x@0 y@4 p@8 なのでサイズは 16（8 バイトアラインメント）
    return s.x + s.y + sizeof(struct S);
}
